let currentLang = localStorage.getItem("studio_lang") || "my";

function t(key) {
    const dict = translations[currentLang] || translations.my;
    return dict[key] || translations.en[key] || key;
}

// tf(key, params): t() with {placeholder} interpolation for dynamic messages.
function tf(key, params) {
    let msg = t(key);
    if (params) {
        for (const [k, v] of Object.entries(params)) {
            msg = msg.split("{" + k + "}").join(String(v));
        }
    }
    return msg;
}

function setLanguage(lang) {
    if (lang !== "my" && lang !== "en") lang = "my";
    currentLang = lang;
    localStorage.setItem("studio_lang", lang);
    // Language class drives Myanmar-safe typography (tall glyph stacks
    // need ~1.9 line-height in toasts/alerts; Latin stays compact).
    document.documentElement.lang = lang === "my" ? "my" : "en";
    document.body.classList.toggle("lang-my", lang === "my");
    document.body.classList.toggle("lang-en", lang === "en");

    // Update toggle button text
    const langBtn = document.getElementById("btn-lang-toggle");
    if (langBtn) {
        langBtn.innerText = lang === "my" ? "🇲🇲 မြန်မာ" : "🇬🇧 EN";
    }

    // Apply to all elements with data-i18n
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (key && translations[lang] && translations[lang][key]) {
            el.innerText = translations[lang][key];
        }
    });

    // Apply placeholders
    document.querySelectorAll("[data-i18n-ph]").forEach(el => {
        const key = el.getAttribute("data-i18n-ph");
        if (key && translations[lang] && translations[lang][key]) {
            el.placeholder = translations[lang][key];
        }
    });

    // Notify backend if user is authenticated. The promise is kept
    // on window so an explicit language toggle can await persistence
    // before re-reading the profile (see toggleLanguage in app.js):
    // without that ordering the profile's stale language_code races
    // back and silently reverts the user's choice.
    if (window.getAuthHeaders) {
        window.__langPersistPromise = fetch("/api/user/language", {
            method: "POST",
            headers: window.getAuthHeaders(),
            body: JSON.stringify({ language: lang }),
        }).catch(() => {});
    }
}
